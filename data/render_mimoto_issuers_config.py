"""Render installations/$INSTALLATION/mimoto-issuers-config.json from its .template.

The only thing that changes with deployment is where the wallet (Inji Web)
is publicly reachable — redirect_uri / token_endpoint both point back at it
(see AGENTS.md's App-level config note). INJI_WEB_URL defaults to localhost
for local dev; a public deployment sets it in vc-stack/.env.

Also renders the two files the public gateway (`api.`) needs so the Inji
mobile wallet can use the same Mimoto/Certify. The phone cannot use Mimoto's
own issuer list or Certify's metadata as-is: both carry Docker-internal URLs
(host.docker.internal, keycloak:8080) that Mimoto needs and Inji Web ignores,
but a phone cannot resolve. Inji Web and Mimoto never go through the gateway
for these two paths, so the gateway serves the phone its own copies and
Mimoto's file is left alone (wiki/architecture/inji-mobile-wallet.md).
"""

from __future__ import annotations

import json
import os
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
CONFIG_DIR = REPO_ROOT / "vc-stack" / "config"
MOBILE_ISSUERS_OUT = CONFIG_DIR / "mimoto-issuers-mobile.json"
GATEWAY_SNIPPET_OUT = CONFIG_DIR / "public-gateway-mobile.conf"

# The app registers this scheme, the Keycloak realm allows it, and the app's own code falls back to it.
MOBILE_REDIRECT_URI = "io.mosip.residentapp.inji://oauthredirect"
# Where Certify's issuer metadata points authorization_servers (Mimoto needs this internal URL).
KEYCLOAK_DOCKER_AUTH_SERVER = "http://keycloak:8080"
MOBILE_MOUNT = "/etc/nginx/mobile"


def render(env: dict[str, str]) -> dict[Path, str]:
    """Return {output path: content} for the given environment."""
    installation_dir = REPO_ROOT / "installations" / env["INSTALLATION"]
    template = installation_dir / "mimoto-issuers-config.json.template"
    inji_web_url = env.get("INJI_WEB_URL", "http://localhost:4004")
    rendered = template.read_text(encoding="utf-8").replace("${INJI_WEB_URL}", inji_web_url)

    api_url = env.get("CERTIFY_PUBLIC_BASE_URL", "http://certify-nginx").rstrip("/")
    keycloak_url = env.get("KEYCLOAK_PUBLIC_BASE_URL", "http://localhost:9080").rstrip("/")
    internal_as = env.get("KEYCLOAK_DOCKER_AUTH_SERVER", KEYCLOAK_DOCKER_AUTH_SERVER).rstrip("/")
    # Local runs have no phone: leave the gateway exactly as it was.
    is_public = api_url.startswith("https://")

    issuer = json.loads(rendered)["issuers"][0]
    if is_public:
        issuer = {
            **issuer,
            "credential_issuer_host": api_url,
            "wellknown_endpoint": f"{api_url}/.well-known/openid-credential-issuer",
            "redirect_uri": MOBILE_REDIRECT_URI,
            "token_endpoint": f"{api_url}/v1/mimoto/get-token/{issuer['issuer_id']}",
        }
    # Same envelope Mimoto's GET /v1/mimoto/issuers returns.
    mobile_list = {"response": {"issuers": [issuer]}, "errors": []}

    if is_public:
        snippet = f"""# Generated by data/render_mimoto_issuers_config.py - do not edit.
# Phone-only views of two api. paths; Mimoto and Inji Web never request them here.
location = /v1/mimoto/issuers {{
    default_type application/json;
    alias {MOBILE_MOUNT}/mimoto-issuers-mobile.json;
}}

# Certify's metadata names the Docker-internal Keycloak, which Mimoto needs; the phone needs the public one.
location = /.well-known/openid-credential-issuer {{
    set $certify_nginx_upstream certify-nginx:80;
    proxy_pass http://$certify_nginx_upstream;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto https;
    proxy_http_version 1.1;
    proxy_set_header Connection "";
    proxy_set_header Accept-Encoding "";
    sub_filter_types application/json;
    sub_filter '"authorization_servers":["{internal_as}/realms/inji"]' '"authorization_servers":["{keycloak_url}/realms/inji"]';
}}
"""
    else:
        snippet = "# Generated by data/render_mimoto_issuers_config.py - local run, nothing to override.\n"

    return {
        installation_dir / "mimoto-issuers-config.json": rendered,
        MOBILE_ISSUERS_OUT: json.dumps(mobile_list, indent=2) + "\n",
        GATEWAY_SNIPPET_OUT: snippet,
    }


def main() -> None:
    for path, content in render(dict(os.environ)).items():
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
