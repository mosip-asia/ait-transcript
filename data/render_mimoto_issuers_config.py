"""Render installations/$INSTALLATION/mimoto-issuers-config.json from its .template.

What changes with deployment is where the wallet (Inji Web) is publicly
reachable — redirect_uri / token_endpoint both point back at it (see
AGENTS.md's App-level config note) — and the Authorization Server, whose
token endpoint and wallet client id come from the installation's
authorization-server.env. INJI_WEB_URL defaults to localhost for local dev;
a public deployment sets it, and any Authorization Server setting, in
vc-stack/.env.

Also renders the two files the public gateway (`api.`) needs so the Inji
mobile wallet can use the same Mimoto/Certify. The phone cannot use Mimoto's
own issuer list or Certify's metadata as-is: both carry Docker-internal URLs
(host.docker.internal, keycloak:8080) that Mimoto needs and Inji Web ignores,
but a phone cannot resolve. Inji Web and Mimoto never go through the gateway
for these two paths, so the gateway serves the phone its own copies and
Mimoto's file is left alone (wiki/architecture/inji-mobile-wallet.md). Only an
installation that carries public-gateway-mobile.conf.template gets them; for any
other the tracked files in vc-stack/config/ are left as they are.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent
CONFIG_DIR = REPO_ROOT / "vc-stack" / "config"
MOBILE_ISSUERS_OUT = CONFIG_DIR / "mimoto-issuers-mobile.json"
GATEWAY_SNIPPET_OUT = CONFIG_DIR / "public-gateway-mobile.conf"

# The app registers this scheme, the Keycloak realm allows it, and the app's own code falls back to it.
MOBILE_REDIRECT_URI = "io.mosip.residentapp.inji://oauthredirect"
MOBILE_MOUNT = "/etc/nginx/mobile"
GENERATED_HEADER = "# Generated by data/render_mimoto_issuers_config.py - do not edit.\n"
# The innermost ${NAME:-default} of a value.
DEFAULTED = re.compile(r"\$\{(\w+):-([^${}]*)\}")


def authorization_server(installation: str, env: dict[str, str]) -> dict[str, str]:
    """The installation's Authorization Server settings, resolved as Compose resolves authorization-server.env.

    Every value is ${KEY:-default}, so a key set (non-empty) in env wins: under Compose env already holds the
    resolved values, on the host the file's stand-in values apply.
    """
    path = REPO_ROOT / "installations" / installation / "authorization-server.env"
    settings = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            key, value = line.split("=", 1)
            while DEFAULTED.search(value):
                value = DEFAULTED.sub(lambda m: env.get(m.group(1)) or m.group(2), value)
            settings[key] = value
    return settings


def render(env: dict[str, str]) -> dict[Path, str]:
    """Return {output path: content} for the given environment."""
    installation_dir = REPO_ROOT / "installations" / env["INSTALLATION"]
    template = installation_dir / "mimoto-issuers-config.json.template"
    values = {"INJI_WEB_URL": env.get("INJI_WEB_URL", "http://localhost:4004"),
              **authorization_server(env["INSTALLATION"], env)}
    rendered = template.read_text(encoding="utf-8")
    for key, value in values.items():
        rendered = rendered.replace("${" + key + "}", value)
    snippet_template = installation_dir / "public-gateway-mobile.conf.template"
    if not snippet_template.is_file():
        return {installation_dir / "mimoto-issuers-config.json": rendered}

    api_url = env.get("CERTIFY_PUBLIC_BASE_URL", "http://certify-nginx").rstrip("/")
    # Local runs have no phone: leave the gateway exactly as it was.
    is_public = api_url.startswith("https://")

    issuer = json.loads(rendered)["issuers"][0]
    if is_public:
        issuer = {
            **issuer,
            "credential_issuer_host": api_url,
            "wellknown_endpoint": f"{api_url}/.well-known/openid-credential-issuer",
            "redirect_uri": MOBILE_REDIRECT_URI,
            "token_endpoint": f"{api_url}/v1/mimoto/get-token/{issuer['issuer_id']}",
        }
    # Same envelope Mimoto's GET /v1/mimoto/issuers returns.
    mobile_list = {"response": {"issuers": [issuer]}, "errors": []}

    if is_public:
        snippet = GENERATED_HEADER + (
            snippet_template.read_text(encoding="utf-8").split("\n", 1)[1]  # drop the template's own source-comment line
            .replace("${MOBILE_MOUNT}", MOBILE_MOUNT)
            .replace("${AUTH_SERVER_ISSUER}", values["AUTH_SERVER_ISSUER"])
            .replace("${AUTH_SERVER_PUBLIC_URL}", values["AUTH_SERVER_PUBLIC_URL"])
        )
    else:
        snippet = "# Generated by data/render_mimoto_issuers_config.py - local run, nothing to override.\n"

    return {
        installation_dir / "mimoto-issuers-config.json": rendered,
        MOBILE_ISSUERS_OUT: json.dumps(mobile_list, indent=2) + "\n",
        GATEWAY_SNIPPET_OUT: snippet,
    }


def main() -> None:
    for path, content in render(dict(os.environ)).items():
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
